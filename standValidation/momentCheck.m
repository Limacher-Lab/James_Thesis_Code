% Scales provide force in units of mass
% Assuming kitchen scale would use 9.81 to go from force to mass so this
% code uses 9.81 to go from mass back to force
grav = 9.81;

% Load cell slopes for converting from Volt to Newton
        % Back   Front
        % G-1232 K-7801
slopes = [29.574 31.820; % Thrust (N/V)
          30.296 32.028;...
          29.3562 30.1330]; % Lift (N/V)

% Load cell slope intercepts
intercepts = [-0.0116 -0.0968; % Thrust (N)
               0.0886 0.2038]; % Lift (N)

% Total measurement capacity of the combined load cells (N)
fullRange = 300;

% Distance from bottom of load cell to top of aluminum plate (mm)
baseArm = 44.9;

% Create list of data sets
dataSets = dir(fullfile('*.mat'));

% Which file names should be kept
dataSetsIdx =...
~contains({dataSets.name}, ["Bias","Post"]);
dataSets = dataSets(dataSetsIdx);
dataSets = struct2table(dataSets);

% Empty containers to hold results
dataLength = length(dataSets.name);
dataTable = zeros(dataLength,3);
dataTable = array2table(dataTable);
dataTable.Properties.VariableNames = ...
    {'Moment Arm' 'Nominal Scale Reading' 'LC Reading'};

% Loop to process results
for testNum = 1:length(dataSets.name)
    % Load file
    tempData = load(fullfile(dataSets.name{testNum}));
    % Extract the file name
    fileName = dataSets.name(testNum);
    % Extract the spring scale reading
    scaleRead = extractAfter(fileName,',');
    scaleRead = scaleRead{1};

    if ~strcmpi(scaleRead,["Bias.mat" "Post.mat"])
        % Format the scale reading and convert to a double
        scaleRead = replace(scaleRead,'_','.');
        scaleRead = replace(scaleRead,'N.mat','');
        scaleRead = str2double(scaleRead);
        
        % Extract length of moment arm from file name
        momentArm = extractBefore(fileName,',');
        momentArm = replace(momentArm,'_','.');
        momentArm = replace(momentArm,'MArm','');
        momentArm = str2double(momentArm)*25.4+baseArm;
        
        % Calculate the forces measured
        xFront = mean(tempData.dataCh3Biased)*slopes(1,1)+intercepts(1,1);
        xBack = mean(tempData.dataCh0Biased)*slopes(1,2)+intercepts(1,2);
        
        yFront = mean(tempData.dataCh4Biased)*slopes(2,1)+intercepts(2,1);
        yBack = mean(tempData.dataCh1Biased)*slopes(2,2)+intercepts(2,2);

        zFront = mean(tempData.dataCh5Biased)*slopes(3,1);
        zBack = mean(tempData.dataCh2Biased)*slopes(3,2);
        
        % Calculate total force measured
        tempLC = sqrt((yFront+yBack)^2+(xFront+xBack)^2+(zFront+zBack)^2);
        
        % Store data
        dataTable.('Moment Arm')(testNum) = momentArm;
        dataTable.('Nominal Scale Reading')(testNum) = scaleRead;
        dataTable.('LC Reading')(testNum) = tempLC;
    end
end

% Create data set for displaying data based on moment arm
momentSort = sortrows(dataTable,"Moment Arm");
% Create filtered data sets for the different scale readings
idx4N = momentSort.("Nominal Scale Reading") == 4.75;
idx8N = momentSort.("Nominal Scale Reading") == 8.5;
idx11N = momentSort.("Nominal Scale Reading") == 11.35;

% Create data set for displaying data based on scale readings
scaleSort = sortrows(dataTable,"Nominal Scale Reading");
% Create filtered data sets for the different moment arms
idx2MA = scaleSort.("Moment Arm") == 2.4*25.4+baseArm;
idx5MA = scaleSort.("Moment Arm") == 5.5*25.4+baseArm;
idx9MA = scaleSort.("Moment Arm") == 9.75*25.4+baseArm;
idx17MA = scaleSort.("Moment Arm") == 17.75*25.4+baseArm;
idx22MA = scaleSort.("Moment Arm") == 22.5*25.4+baseArm;

% Calculate the percent difference as a function of the full range
momentSort.("Percent Diff") = ...
    (...
        momentSort.("LC Reading")-...
        momentSort.("Nominal Scale Reading")...
    )./fullRange*100;

% Plot the figures
figure()
hold on
a1 = ...
    plot(...
        momentSort.("Moment Arm")(idx4N),...
        momentSort.("Percent Diff")(idx4N),...
        '-o',...
        DisplayName='4.75N Spring Scale Reading'...
