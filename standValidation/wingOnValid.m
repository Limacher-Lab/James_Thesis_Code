imgLoc = ['C:\Users\James\OneDrive - ' ... % Location to export figures
    'University of Calgary\Thesis\Calibration Images\'];

% Scales provide force in units of mass
% Assuming kitchen scale would use 9.81 to go from force to mass so this
% code uses 9.81 to go from mass back to force
grav = 9.81;

% Load cell slopes for converting from Volt to Newton
        % Back   Front
        % G-1232 K-7801
slopes = [29.574 31.820; % Thrust (N/V)
          30.296 32.028]; % Lift (N/V)

% Load cell slope intercepts
intercepts = [-0.0116 -0.0968; % Thrust (N)
               0.0886 0.2038]; % Lift (N)

% Uncertainty in the slope of the load cell
slopesUnc = [0.0294 0.0388; % Thrust (N/V)
             0.0208 0.0410]; % Lift (N/V)

% Uncertainty in the intercepts of the load cell
interUnc = [0.0878 0.0949; % Thrust (N)
            0.0904 0.1202]; % Lift (N)

% Posible misalignment estimates in degrees
sensorMisalignDeg = 1.7;

pulleyMisalignDeg = 10;

% Coefficient of static friction
mu = 0.11;

% Equation to numerically solve for angle the pulley makes with the
% vertical, and removing solutions where theta < 0
syms t;
thetaEqn = (sin(t)-cos(t))/(sin(t)+cos(t)-1)==mu;
theta = solve(thetaEqn, t,Real=true);
theta =rad2deg(double(theta));
theta(theta<0)=[];

% Solving beta and eta based on the numerical solution of theta
beta = sind(theta)-mu*cosd(theta);
eta = 1/(1+mu/beta);

% Empty containers to hold data processing results
dataSets = dir(fullfile('*.mat'));
dataSets = struct2table(dataSets);

dataLength = length(dataSets.name);
dataTable = zeros(dataLength,5);
dataTable = array2table(dataTable);
dataTable.Properties.VariableNames = {'Axis' 'Direction' 'ActMass'...
    'MeasMass' 'ErrBar'};
dataTable = convertvars(dataTable,["Axis" "Direction"],'string');

% Loop to process all data files
for setNum = 1:length(dataSets.name)
    % Load the file and extract filename
    tempData = load(fullfile(dataSets.name{setNum}));
    fileName = dataSets.name(setNum);
    
    % Extract information from the filename
    direction = extractBefore(fileName,',');% Positive of Negative
    fileName = extractAfter(fileName,',');
    axis = extractBefore(fileName,',');% Axis tested
    fileName = extractAfter(fileName,',');
    idx = strfind(fileName,".");
    mass = str2double(extractBefore(fileName,idx{end}(end)))*grav; % Force
    
    % Flip sign of force if applied in negative direction
    if direction=="Neg"
        mass = -mass;
    end
    % Take mean of measured voltages and convert to forces
    xFront = mean(tempData.dataCh3Biased)*slopes(1,1)+intercepts(1,1);
    xBack = mean(tempData.dataCh0Biased)*slopes(1,2)+intercepts(1,2);
    yFront = mean(tempData.dataCh4Biased)*slopes(2,1)+intercepts(2,1);
    yBack = mean(tempData.dataCh1Biased)*slopes(2,2)+intercepts(2,2);

    thrustMisalignSense = ...
        (...
            (yFront+yBack)*cosd(sensorMisalignDeg)-...
            (xFront+xBack)*sind(sensorMisalignDeg)...
         )/cosd(pulleyMisalignDeg);
    thrustMisalignPulley = ...
        (...
            (yFront+yBack)*sind(sensorMisalignDeg)+...
            (xFront+xBack)*cosd(sensorMisalignDeg)...
         )*(sind(pulleyMisalignDeg)/(cosd(pulleyMisalignDeg)^2));
    liftMisalignSense = ...
        (...
            -(yFront+yBack)*sind(sensorMisalignDeg)-...
            (xFront+xBack)*cosd(sensorMisalignDeg)...
        )/cosd(pulleyMisalignDeg);
    liftMisalignPulley = ...
        (...
            (yFront+yBack)*cosd(sensorMisalignDeg)-...
            (xFront+xBack)*sind(sensorMisalignDeg)...
         )*(sind(pulleyMisalignDeg)/(cosd(pulleyMisalignDeg)^2));
    % Find sum of load cells force measured and calculate the uncertainty
    if string(axis)=='X'
        tempMeasMass = (xFront+xBack);
        tempErrBar = ...
            sqrt(...
              (mean(tempData.dataCh3Biased)/cosd(pulleyMisalignDeg))^2*slopesUnc(1,1)^2+...
              (mean(tempData.dataCh0Biased)/cosd(pulleyMisalignDeg))^2*slopesUnc(1,2)^2+...
              (interUnc(1,1)/cosd(pulleyMisalignDeg))^2+...
              (interUnc(1,2)/cosd(pulleyMisalignDeg))^2+...
              thrustMisalignSense^2*deg2rad(sensorMisalignDeg)^2+...
              thrustMisalignPulley^2*deg2rad(pulleyMisalignDeg)^2 ...
            );
    elseif string(axis)=='Y'
        tempMeasMass = (yFront+yBack);
        tempErrBar = ...
            sqrt(...
              (mean(tempData.dataCh4Biased)/cosd(pulleyMisalignDeg))^2*slopesUnc(2,1)^2+...
              (mean(tempData.dataCh1Biased)/cosd(pulleyMisalignDeg))^2*slopesUnc(2,2)^2+...
              (interUnc(2,1)/cosd(pulleyMisalignDeg))^2+...
              (interUnc(2,2)/cosd(pulleyMisalignDeg))^2+...
              liftMisalignSense^2*deg2rad(sensorMisalignDeg)^2+...
              liftMisalignPulley^2*deg2rad(pulleyMisalignDeg)^2 ...
            );
    end

    % Store the data
    dataTable.Axis(setNum) = axis;
    dataTable.Direction(setNum) = direction;
    dataTable.ActMass(setNum) = mass;
    dataTable.MeasMass(setNum) = tempMeasMass;
    dataTable.ErrBar(setNum) = tempErrBar;

end

% Sort the table by the applied force (mass)
dataTable = sortrows(dataTable,"ActMass");

% Fit data to plot a line of best fit through the data and compare the
% slope of the best fit line to the prediction created about (eta)
[xSlope, xFit] = ...
    polyfit(...
        dataTable(dataTable.Axis=='X',:).ActMass,...
        dataTable(dataTable.Axis=='X',:).MeasMass,...
        1 ...
     );
xVal = polyval(xSlope,-5.1:0.1:5.1);

[ySlope, yFit] = ...
    polyfit(...
        dataTable(dataTable.Axis=='Y',:).ActMass,...
        dataTable(dataTable.Axis=='Y',:).MeasMass,...
        1 ...
    );
yVal = polyval(ySlope,-5.1:0.1:5.1);

% Finding uncertainty bars for the different axes
vertErrX = abs(dataTable(dataTable.Axis=='X',:).ErrBar);
vertErrY = abs(dataTable(dataTable.Axis=='Y',:).ErrBar);

% Plotting results
figure()
hold on
plot(...
    dataTable(dataTable.Axis=='X',:).ActMass,...
    dataTable(dataTable.Axis=='X',:).ActMass,...
    '-b',...
    DisplayName='Actual Mass'...
)
plot(...
    dataTable(dataTable.Axis=='X',:).ActMass,...
    eta*dataTable(dataTable.Axis=='X',:).ActMass,...
    '-r',...
    DisplayName=sprintf('Friction Loss Estimate ($\\mu_s$=%.2f)',mu)...
)
plot(...
    dataTable(dataTable.Axis=='X',:).ActMass,...
    dataTable(dataTable.Axis=='X',:).MeasMass,...
    '--^g',...
    DisplayName='Measured Mass' ...
)
errorbar( ...
    dataTable(dataTable.Axis=='X',:).ActMass, ...
    dataTable(dataTable.Axis=='X',:).MeasMass, ...
    vertErrX, ...
    'k', ...
    'LineStyle','none', ...
    'HandleVisibility','off' ...
)
xlabel('$T_{load}$ (N)')
ylabel('$T_{meas}$ (N)')
legend
xticks(-50:10:50)
